/** Lấy các mục hướng dẫn mà tài khoản hiện tại được xem */
export function visibleGuideSections(can, pagePerms) {
  return GUIDE_SECTIONS.filter((sec) => {
    if (!sec.page) return true;
    if (sec.page === "cashier_home") {
      return (can("pos_sale", "create") || can("pos_sale", "edit") ||
              ["pos_orders", "pos_collect", "pos_reconcile"].some(r => can(r, "view")));
    }
    const perm = pagePerms?.[sec.page];
    if (!perm) return true;
    return !!can(perm[0], perm[1]);
  });
}
